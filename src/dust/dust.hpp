// forward declarations
class Driver;
class MeshBlockPack;
class ShearingBoxCC;

// constants that enumerate particle-mesh deposit schemes
enum class DustDeposit {ngp=0, cic=1, tsc=2};

// contract for per-particle stopping times.  The default species_fixed mode keeps the
// configured species table authoritative; particle_static permits arbitrary positive
// per-particle values that remain constant; dynamic refreshes their global maximum once
// per cycle.
enum class DustStoppingTimeMode {species_fixed=0, particle_static=1, dynamic=2};

// `local` is the regression baseline. `applya` executes one non-mutating coupled
// operator application and then retains the local answer, for marginal-cost timing.
enum class DustDragSolver {local=0, applya=1, dc1=2, pcg=3, adaptive=4};

// Stage-frozen particle-mesh transfer cache. The arrays use a structure-of-arrays
// layout, (quantity, particle), so adjacent particle threads read contiguous values.
// Indices refer to the central PM cell; wx/wy/wz each occupy three consecutive slots.
enum DustPMCacheIndex {pm_cache_m=0, pm_cache_ip=1, pm_cache_jp=2, pm_cache_kp=3,
                       npm_cache_index=4};
enum DustPMCacheReal {pm_cache_wx=0, pm_cache_wy=3, pm_cache_wz=6, pm_cache_cj=9,
                      pm_cache_muc=10, pm_cache_mu=11, npm_cache_real=12};

